#!/usr/bin/env bash
# One sample, every depth, three profilers.
#
#   scripts/depth-bench/ladder.sh <sample> <R1.gz> <R2.gz> [threads]
#
# The question is what a PEEK recovers: the page caps a run at 3 million reads by
# default, and nothing so far says what that costs. So the same reads are
# subsampled at eight depths around the cap and profiled three ways — the page's
# own catalogue, the whole of GTDB, and a gene-catalogue profiler that works by a
# different principle entirely — plus the page's functional profile at each
# depth.
#
# Subsamples are written, used and deleted one at a time: the ladder sums to 2.7x
# the run, and this machine has 8 GB free. The sketches are kept, because sylph
# profiles many sketches against one database in a single load, and the GTDB
# database is 14 GB to read.
# DO NOT EDIT THIS FILE WHILE A LADDER IS RUNNING. bash reads a script
# incrementally, by byte offset: an edit shifts everything after it and the
# running interpreter resumes in the middle of a different line. It happened
# here — the post-subsample check ran after the rung had deleted its files, and
# the "échelle terminée" line at the end was never reached, so the queued
# ladders never started. The rungs themselves survived, which is the dangerous
# part: nothing said the script had been derailed. Copy the file, edit the copy.
set -euo pipefail

SAMPLE=$1; R1=$2; R2=$3; THREADS=${4:-10}
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
BENCH=$ROOT/data/bench
SEQTK=/home/ggautreau/miniconda3/envs/seqtk_env/bin/seqtk
SYLPH=/home/ggautreau/miniconda3/envs/sylph/bin/sylph
METEOR=/home/ggautreau/miniconda3/envs/meteor/bin/meteor
REF_METEOR=$BENCH/refs/hs_10_4_gut_taxo

DEPTHS="100000 250000 500000 1000000 2000000 3000000 5000000 6500000"

# THE INPUT, BEFORE ANY OF IT IS BELIEVED.
#
# A download of ERR14098640_1.fastq.gz arrived at exactly the byte count the
# archive publishes and was corrupt anyway — gzip stopped with a CRC error at
# 4.9 of its 7.96 million reads. seqtk does not fail on that: it samples from
# what it could read, so every rung of that ladder drew its R1 from a 4.9 M pool
# and its R2 from a 7.96 M one. Nothing threw, nothing logged, and the profiles
# looked entirely reasonable. Two hours of compute produced a sample that had to
# be discarded.
#
# So both mates are tested here, and their record counts compared, before a
# single rung is climbed. `gzip -t` reads the whole file: about a minute for a
# gigabyte, against the hours it protects.
echo "[$SAMPLE] vérification des entrées"
for F in "$R1" "$R2"; do
  gzip -t "$F" || { echo "[$SAMPLE] ARCHIVE CORROMPUE : $F"; exit 3; }
done
N1=$(zcat "$R1" | wc -l)
N2=$(zcat "$R2" | wc -l)
if [ "$N1" != "$N2" ]; then
  echo "[$SAMPLE] LES MATES NE CORRESPONDENT PAS : $((N1/4)) contre $((N2/4)) lectures"
  exit 3
fi
echo "[$SAMPLE] $((N1/4)) paires, les deux mates concordent"
WORK=$BENCH/work/$SAMPLE
OUT=$BENCH/out/$SAMPLE
mkdir -p "$WORK" "$OUT/sketch" "$OUT/func" "$OUT/meteor" "$OUT/log"

for D in $DEPTHS; do
  TAG="${SAMPLE}_d${D}"
  if [ -f "$OUT/log/$TAG.done" ]; then echo "[$TAG] déjà fait"; continue; fi
  echo "[$TAG] sous-échantillonnage"
  # Same seed on both mates keeps the pairs together: seqtk draws the same record
  # indices, so read i of R1 and read i of R2 are the two ends of one fragment.
  "$SEQTK" sample -s42 "$R1" "$D" | gzip -1 > "$WORK/${TAG}_1.fastq.gz"
  "$SEQTK" sample -s42 "$R2" "$D" | gzip -1 > "$WORK/${TAG}_2.fastq.gz"
  # And again on the way out: a full disk truncates a subsample without seqtk or
  # gzip returning anything a shell would notice.
  S1=$(zcat "$WORK/${TAG}_1.fastq.gz" | wc -l)
  S2=$(zcat "$WORK/${TAG}_2.fastq.gz" | wc -l)
  WANT=$(( D * 4 ))
  [ "$S1" = "$S2" ] && { [ "$S1" = "$WANT" ] || [ "$S1" = "$N1" ]; } || {
    echo "[$TAG] SOUS-ÉCHANTILLON INCOHÉRENT : $((S1/4)) / $((S2/4)) pour $D demandées"
    exit 4
  }

  echo "[$TAG] sylph sketch"
  "$SYLPH" sketch -1 "$WORK/${TAG}_1.fastq.gz" -2 "$WORK/${TAG}_2.fastq.gz" \
    -c 200 -k 31 -t "$THREADS" -d "$OUT/sketch" -S "$TAG" \
    > "$OUT/log/$TAG.sketch.log" 2>&1

  echo "[$TAG] fonctions (le code de la page)"
  node "$ROOT/scripts/depth-bench/func_profile.mjs" \
    "$WORK/${TAG}_1.fastq.gz" "$WORK/${TAG}_2.fastq.gz" "$OUT/func/$TAG.json" \
    >> "$OUT/log/$TAG.func.log" 2>&1

  echo "[$TAG] meteor"
  rm -rf "$WORK/mt"
  mkdir -p "$WORK/mt/in"
  ln -sf "$WORK/${TAG}_1.fastq.gz" "$WORK/mt/in/${TAG}_1.fastq.gz"
  ln -sf "$WORK/${TAG}_2.fastq.gz" "$WORK/mt/in/${TAG}_2.fastq.gz"
  "$METEOR" fastq -i "$WORK/mt/in" -p -o "$WORK/mt/fq" > "$OUT/log/$TAG.meteor.log" 2>&1
  "$METEOR" mapping -i "$WORK/mt/fq/$TAG" -r "$REF_METEOR" -o "$WORK/mt/map" \
    -t "$THREADS" >> "$OUT/log/$TAG.meteor.log" 2>&1
  "$METEOR" profile -i "$WORK/mt/map/$TAG" -r "$REF_METEOR" -o "$WORK/mt/prof" \
    >> "$OUT/log/$TAG.meteor.log" 2>&1
  cp "$WORK/mt/prof/$TAG/${TAG}_msp.tsv.xz" "$OUT/meteor/$TAG.msp.tsv.xz"
  cp "$WORK/mt/prof/$TAG/${TAG}_census_stage_2.json" "$OUT/meteor/$TAG.census.json"

  rm -rf "$WORK/mt" "$WORK/${TAG}_1.fastq.gz" "$WORK/${TAG}_2.fastq.gz"
  touch "$OUT/log/$TAG.done"
  echo "[$TAG] fait — $(df -h / | awk 'NR==2{print $4}') libre"
done
echo "[$SAMPLE] échelle terminée"
